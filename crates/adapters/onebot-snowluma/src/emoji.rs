//! QQ 系统表情 id → 人话。
//!
//! 平台只给编号（`5`、`424`），投递里直接甩编号等于没给。这里维护一张表：认得的
//! 给名字，认不得的保留编号并标「未知」——既让人看懂，也让以后补表时能从投递里
//! 直接看到哪个 id 还没收录。
//!
//! ## 表从哪来
//!
//! SnowLuma 本身有可靠的查询入口：`fetch_sys_faces`（`face.system_list`，系统表情
//! 目录）和 `fetch_face_entity`（`face.entity`，按编号查单个表情，返回名称/别名）。
//! 但它们是**上行动作**，只能在动作链路里请求/响应；入站事件的解析是同步的，不能
//! 为了给一个表情补名字去等一次网络往返，也不该为此给事件入库排队。所以这里用一张
//! 内置表兜底。
//!
//! 表的来源是 QQNT 表情目录（QFace `_index.json`，2026-09-28 同步）：取其中
//! **编号为纯数字、且未隐藏**的 265 项，覆盖 0–507。`424` 是动画/超级表情包里的
//! 「续标识」，与它同类的还有 `423 复兴号`、`425 求放过` 等。
//!
//! ## 以后怎么补
//!
//! 新表情上线后，按下面任一方式重新生成 [`SYSTEM_FACES`] 并替换即可：
//!
//! 1. 从 `https://koishi.js.org/QFace/` 的 `_index.json` 取 `emojiId` / `describe`，
//!    跳过 `isHide: true` 和非纯数字 id；
//! 2. 或从 SnowLuma `face.system_list` 的返回里取 `id` / `name`（同一个目录的
//!    运行时版本，最权威）。
//!
//! 未知 id 的投递文本里会原样保留编号并标「未知」，照着投递里的编号补最容易。

